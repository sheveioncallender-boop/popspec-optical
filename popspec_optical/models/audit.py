import json
from odoo import api, fields, models, _
from odoo.exceptions import AccessError, UserError


class OpticalMixin(models.AbstractModel):
    _name = 'optical.mixin'
    _description = 'Optical attribution and audit helpers'

    def _require_group(self, xmlid):
        if not self.env.user.has_group('popspec_optical.' + xmlid):
            raise AccessError(_('Your optical role does not allow this action.'))

    def _employee(self, company):
        # Do not grant access to private HR records to optical staff.
        employees = self.env['hr.employee'].sudo().search([
            ('user_id', '=', self.env.uid), ('company_id', '=', company.id),
        ], limit=2)
        if len(employees) != 1:
            raise UserError(_('Link your own user to one employee in this company before recording optical work.'))
        return employees

    def _lock(self):
        self.check_access('write')
        self.flush_recordset()
        # Table name is a model constant, never supplied by the browser.
        self.env.cr.execute('SELECT id FROM "%s" WHERE id IN %%s ORDER BY id FOR UPDATE' % self._table,
                            [tuple(self.ids)])
        self.invalidate_recordset()

    def _audit(self, action, detail=None, clinical=False):
        for record in self:
            self.env['optical.audit']._record({
                'company_id': record.company_id.id,
                'actor_id': self.env.uid,
                'employee_id': self._employee(record.company_id).id,
                'model_name': record._name, 'record_id': record.id,
                'record_name': record.display_name, 'action': action,
                'clinical': clinical, 'details': json.loads(json.dumps(detail or {}, default=str)),
            })


class OpticalAudit(models.Model):
    _name = 'optical.audit'
    _description = 'Optical Audit Event'
    _order = 'id desc'
    company_id = fields.Many2one('res.company', required=True, index=True)
    occurred_at = fields.Datetime(default=fields.Datetime.now, required=True, readonly=True)
    actor_id = fields.Many2one('res.users', required=True, readonly=True, ondelete='restrict')
    employee_id = fields.Many2one('hr.employee', required=True, readonly=True, ondelete='restrict')
    model_name = fields.Char(required=True, readonly=True)
    record_id = fields.Integer(required=True, readonly=True)
    record_name = fields.Char(readonly=True)
    action = fields.Char(required=True, readonly=True)
    clinical = fields.Boolean(readonly=True)
    details = fields.Json(readonly=True)

    @api.model
    def _record(self, values):
        return super(OpticalAudit, self.sudo()).create(values)

    @api.model_create_multi
    def create(self, vals_list):
        raise AccessError(_('Audit events can only be generated by optical operations.'))

    def write(self, vals):
        raise AccessError(_('Audit events cannot be edited.'))

    def unlink(self):
        raise AccessError(_('Audit events cannot be deleted.'))
